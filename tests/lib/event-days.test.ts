import { describe, expect, it } from 'vitest'
import { eventOpenWeekdays } from '~/lib/event-days'

// 실데이터(data/index.json)의 time 문구
describe('eventOpenWeekdays', () => {
  it.each([
    ['화-일 10:00~18:00 / 월요일 휴관', [0, 2, 3, 4, 5, 6]],
    ['11:00 ~ 18:00, 월요일 휴관', [0, 2, 3, 4, 5, 6]],
    ['12:00~18:00(일,월 휴관)', [2, 3, 4, 5, 6]],
    ['매주 (토) 14:00~17:00 / 공연발표 29(일) 10:00~17:00', [6]],
    ['매주 화요일 10:00, 14:00 (11.3(화)는 단체 예약으로 예약 불가)', [2]],
    ['월,수,목 19:30 / 금 15:00, 19:30 / 토,일 15:00', [0, 1, 3, 4, 5, 6]],
    ['평일 14:00~20:00 / 주말 12:00~20:00 ※월요일 휴관', [0, 2, 3, 4, 5, 6]],
    ['10:00~18:00, 일요일 및 공휴일 휴관', [1, 2, 3, 4, 5, 6]],
    ['매주 주말 및 공휴일 15:00 (6월~8월 제외)', [0, 6]],
    ['11:00~19:00(10.30.(금) 21:00까지 연장운영, 11.01.(일) 15:00까지 단축운영)', null],
    ['10:00~18:00 / 휴관일: 매주 월요일', null],
    ['11:00~19:00, 목요일 21:00까지 연장', null],
    ['10:00~18:00 (금요일은 21:00까지)', null],
    ['(토·일 21:00까지 연장)', null],
    ['화요일부터 일요일까지', [0, 2, 3, 4, 5, 6]],
    ['(일 2회)', null],
    ['토,일 2회', [0, 6]],
    ['10:00~18:00', null],
    ['종일', null],
    [undefined, null],
  ])('%s → %j', (time, expected) => {
    expect(eventOpenWeekdays(time)).toEqual(expected)
  })

  it('여는 요일과 쉬는 요일이 엇갈려도 빈 배열은 내지 않는다', () => {
    expect(eventOpenWeekdays('수-일 12:00~19:00, 매주 월·화 휴관')).not.toEqual([])
  })
})
